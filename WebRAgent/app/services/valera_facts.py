"""
Паспорт Валеры и карточка опорных фактов — для системных промптов.

Зачем. Облачная/локальная модель отвечает «из головы», когда в найденных
чанках нет нужного факта, и выдумывает имена (в логах: «ректор — Кузнецов»,
«Кудышев»). Короткая карточка с проверенными фактами в КАЖДОМ промпте убирает
самые частые ошибки без поиска по базе.

Правила: пишем коротко (≈150 слов), всё кириллицей (синтезатор речи читает
«Юнитри Аш-один», а не «Unitree H1»), датированные факты считаем от сегодня.
Источник фактов — knowledge_base/rtu_mirea_llm_kb (chunks 80–86); при смене
фактов правьте этот файл и фрагменты вместе.
"""


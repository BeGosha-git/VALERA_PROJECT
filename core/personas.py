    "существу. "
    # Краткость задаётся ЗДЕСЬ, а не обрезкой ответа после генерации
    "Говори кратко: обычно 1-2 предложения, максимум 40 слов. "
    "Никаких служебных концовок — «если есть вопросы, обращайтесь», "
    "«рад был помочь», «спрашивай» — закончил мысль и остановился. "
